package dev.stanislav.focusdeck.qa

import android.content.Context
import android.content.ContextWrapper
import android.content.SharedPreferences
import android.os.Bundle
import androidx.lifecycle.ViewModelProvider
import androidx.lifecycle.ViewModelStore
import androidx.room.Room
import dev.stanislav.focusdeck.data.db.FocusDeckDatabase
import dev.stanislav.focusdeck.data.db.Meal
import dev.stanislav.focusdeck.data.db.MealType
import dev.stanislav.focusdeck.data.repo.NutritionRepository
import dev.stanislav.focusdeck.ui.nutrition.NutritionViewModel
import kotlinx.coroutines.async
import kotlinx.coroutines.coroutineScope
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import kotlinx.coroutines.withTimeout

/** Runs only in the test APK and in a separate disposable database, never focusdeck.db. */
internal object NutritionRetryProbe {
    private const val DATABASE = "focusdeck-nutrition-idempotency-qa.db"

    fun run(context: Context, main: (() -> Unit) -> Unit): Bundle = runBlocking {
        check(context.packageName == "dev.stanislav.focusdeck.qa")
        val isolated = object : ContextWrapper(context) {
            override fun getApplicationContext(): Context = this
            override fun getSharedPreferences(name: String, mode: Int): SharedPreferences =
                super.getSharedPreferences("qa_nutrition_probe_$name", mode)
        }
        val prefs = isolated.getSharedPreferences("nutrition_drafts", Context.MODE_PRIVATE)
        check(prefs.edit().clear().commit())
        var store = ViewModelStore()
        var stage = "Room replay"
        var observedModel: NutritionViewModel? = null
        context.deleteDatabase(DATABASE)
        var db = Room.databaseBuilder(context, FocusDeckDatabase::class.java, DATABASE).build()
        try {
            var repository = NutritionRepository(context, db.mealDao(), db.weightDao())
            val meal = Meal(id = -92026092901L, dayEpochDay = 20725L,
                type = MealType.LUNCH, name = "QA isolated retry meal", calories = 520,
                epochMillis = 1790630000000L)
            check(repository.addMealOnce(meal) == meal)
            db.close()
            // Reopen with new Room/repository instances: no in-memory operation cache survives.
            db = Room.databaseBuilder(context, FocusDeckDatabase::class.java, DATABASE).build()
            repository = NutritionRepository(context, db.mealDao(), db.weightDao())
            check(repository.addMealOnce(meal) == meal)
            check(repository.observeMealsForDay(meal.dayEpochDay).first() == listOf(meal))
            val collision = runCatching { repository.addMealOnce(meal.copy(calories = 521)) }
            check(collision.isFailure)
            check(repository.observeMealsForDay(meal.dayEpochDay).first() == listOf(meal))
            coroutineScope {
                val a = async { repository.addMealOnce(meal) }
                val b = async { repository.addMealOnce(meal) }
                check(a.await() == meal && b.await() == meal)
            }
            check(repository.observeMealsForDay(meal.dayEpochDay).first().size == 1)
            val edited = meal.copy(calories = 530)
            repository.updateMeal(edited)
            check(repository.observeMealsForDay(meal.dayEpochDay).first() == listOf(edited))
            repository.deleteMeal(edited)
            check(repository.observeMealsForDay(meal.dayEpochDay).first().isEmpty())
            val generated = repository.addMeal(meal.dayEpochDay, MealType.DINNER,
                "QA ordinary autogenerated meal", 400)
            check(generated > 0L)
            check(repository.observeMealsForDay(meal.dayEpochDay).first().single().id == generated)
            // Recreate the exact durable boundary: Room insert succeeded, draft cleanup did not.
            val recovered = meal.copy(id = -92026092902L, dayEpochDay = 20726L)
            repository.addMealOnce(recovered)
            val key = "draft_${recovered.dayEpochDay}_new"
            check(prefs.edit().putLong("selected_day", recovered.dayEpochDay)
                .putString("${key}_name", recovered.name)
                .putString("${key}_calories", recovered.calories.toString())
                .putString("${key}_type", recovered.type.name)
                .putLong("${key}_creation_id", recovered.id)
                .putLong("${key}_creation_time", recovered.epochMillis)
                .putBoolean("${key}_inflight", true).commit())
            lateinit var model: NutritionViewModel
            main { model = ViewModelProvider(store, NutritionViewModel.Factory(repository, isolated))[NutritionViewModel::class.java] }
            observedModel = model
            stage = "initial model loading"
            withTimeout(10_000) { while (model.uiState.value.loading) delay(10) }
            check(model.uiState.value.draft.requiresRecovery)
            check(!model.uiState.value.draft.editable(false, false))
            main { model.saveMeal() }
            stage = "draft recovery completion"
            withTimeout(10_000) { while (model.uiState.value.busy || model.uiState.value.draft.requiresRecovery) delay(10) }
            check(repository.observeMealsForDay(recovered.dayEpochDay).first() == listOf(recovered))
            check(model.uiState.value.draft.name.isEmpty())
            check(!prefs.contains("${key}_creation_id"))
            main { store.clear() }
            store = ViewModelStore()
            main { model = ViewModelProvider(store, NutritionViewModel.Factory(repository, isolated))[NutritionViewModel::class.java] }
            observedModel = model
            stage = "recreated model loading"
            withTimeout(10_000) { while (model.uiState.value.loading) delay(10) }
            check(!model.uiState.value.draft.requiresRecovery && model.uiState.value.draft.name.isEmpty())
            main { model.updateWeight(recovered.dayEpochDay, "73,5") }
            stage = "unreserved weight draft durability"
            withTimeout(10_000) {
                while (!model.weightDraft.value.draftSaved) delay(10)
            }
            main { store.clear() }
            store = ViewModelStore()
            main { model = ViewModelProvider(store, NutritionViewModel.Factory(repository, isolated))[NutritionViewModel::class.java] }
            observedModel = model
            check(model.weightDraft.value.text == "73,5" && model.weightDraft.value.creationId == null)
            main { model.saveWeight(recovered.dayEpochDay) }
            stage = "weight success"
            withTimeout(10_000) { while (model.weightDraft.value.busy) delay(10) }
            check(model.weightDraft.value.text.isEmpty() && model.weightDraft.value.error == null)
            check(repository.observeRecentWeights().first().single().kg == 73.5f)
            db.openHelper.writableDatabase.execSQL(
                "CREATE TRIGGER qa_fail_weight BEFORE INSERT ON weight_entries BEGIN SELECT RAISE(ABORT, 'QA forced weight write failure'); END",
            )
            main { model.updateWeight(recovered.dayEpochDay, "74,2"); model.saveWeight(recovered.dayEpochDay) }
            stage = "weight failure retention"
            withTimeout(10_000) { while (model.weightDraft.value.busy) delay(10) }
            check(model.weightDraft.value.text == "74,2" && model.weightDraft.value.error != null)
            val reservedWeight = model.weightDraft.value.reservedEntry()
            val weightKey = "weight_${recovered.dayEpochDay}"
            check(prefs.getLong("${weightKey}_creation_id", 0L) == reservedWeight.id)
            main { store.clear() }
            store = ViewModelStore()
            main { model = ViewModelProvider(store, NutritionViewModel.Factory(repository, isolated))[NutritionViewModel::class.java] }
            observedModel = model
            stage = "weight failure after recreation"
            check(model.weightDraft.value.text == "74,2")
            check(model.weightDraft.value.reservedEntry() == reservedWeight)
            main { model.updateWeight(recovered.dayEpochDay, "99") }
            check(model.weightDraft.value.text == "74,2")
            db.openHelper.writableDatabase.execSQL("DROP TRIGGER qa_fail_weight")
            main { model.saveWeight(recovered.dayEpochDay); model.saveWeight(recovered.dayEpochDay) }
            stage = "weight reserved retry"
            withTimeout(10_000) { while (model.weightDraft.value.busy) delay(10) }
            check(model.weightDraft.value.text.isEmpty() && model.weightDraft.value.error == null)
            check(!prefs.contains("${weightKey}_creation_id"))
            check(repository.observeRecentWeights().first().count { it.id == reservedWeight.id } == 1)
            check(repository.addWeightOnce(reservedWeight) == reservedWeight)
            check(runCatching { repository.addWeightOnce(reservedWeight.copy(kg = 99f)) }.isFailure)
            check(repository.observeRecentWeights().first().single { it.id == reservedWeight.id } == reservedWeight)
            // Insert already committed but cleanup interrupted: seed the durable operation and recreate.
            main { store.clear() }
            check(prefs.edit().putString("${weightKey}_text", "74,2")
                .putLong("${weightKey}_creation_id", reservedWeight.id)
                .putLong("${weightKey}_creation_time", reservedWeight.epochMillis).commit())
            store = ViewModelStore()
            main { model = ViewModelProvider(store, NutritionViewModel.Factory(repository, isolated))[NutritionViewModel::class.java] }
            observedModel = model
            main { model.saveWeight(recovered.dayEpochDay) }
            stage = "weight committed boundary recovery"
            withTimeout(10_000) { while (model.weightDraft.value.busy) delay(10) }
            check(model.weightDraft.value.text.isEmpty() && model.weightDraft.value.error == null)
            check(repository.observeRecentWeights().first().count { it.id == reservedWeight.id } == 1)
            check(!prefs.contains("${weightKey}_text"))
            Bundle().apply {
                putString("status", "ok")
                putString("text", "15 checks: persistent replay, collision refusal, concurrent replay, negative-ID edit/delete, positive autoincrement, durable draft recovery, model recreation, unreserved weight draft recreation, weight success, weight failure retains input, weight failure recreation, immutable reservation, weight retry/double tap, weight replay/collision, weight committed-boundary recovery")
            }
        } catch (failure: Exception) {
            val state = observedModel?.uiState?.value
            throw IllegalStateException("$stage: ${failure.message}; loading=${state?.loading}, busy=${state?.busy}, recovery=${state?.draft?.requiresRecovery}, error=${state?.error}", failure)
        } finally {
            main { store.clear() }
            db.close()
            context.deleteDatabase(DATABASE)
            prefs.edit().clear().commit()
        }
    }
}
